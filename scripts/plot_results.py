def main() -> int:
    parser = argparse.ArgumentParser(description="Gera gráficos dos resultados do SMA.")
    parser.add_argument("--results-dir", type=Path, help="Caminho do diretório de resultados (ex: results/trd_20260617_155000)")
    args = parser.parse_args()

    root_dir = Path(__file__).resolve().parents[1]
    
    results_dir = args.results_dir
    if not results_dir:
        latest = get_latest_results_dir(root_dir)
        if not latest:
            print("Erro: Nenhum diretório de resultados encontrado em 'results/'. Rode os experimentos primeiro.", file=sys.stderr)
            return 1
        results_dir = latest

    print(f"Lendo resultados de: {results_dir}")
    
    output_plots_dir = results_dir / "plots"
    output_plots_dir.mkdir(exist_ok=True)

    plot_convergence(results_dir, output_plots_dir)
    plot_fitness_distribution(results_dir, output_plots_dir)
    plot_execution_time(results_dir, output_plots_dir)

    print(f"\nTodos os gráficos foram salvos na pasta: {output_plots_dir}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
