#!/usr/bin/env python3
"""Plot results from TRD blackboard experiments.

This script reads the CSVs generated by run_experiments.py and creates
publication-quality plots (PNG and PDF) for academic articles.
"""

import argparse
import sys
from pathlib import Path
import matplotlib.pyplot as plt
import pandas as pd

# Set academic style for matplotlib
plt.rcParams.update({
    "font.size": 11,
    "axes.labelsize": 12,
    "axes.titlesize": 12,
    "xtick.labelsize": 10,
    "ytick.labelsize": 10,
    "legend.fontsize": 10,
    "figure.titlesize": 14,
    "font.family": "serif",
    "text.usetex": False,  # Avoid requiring full LaTeX installation
    "axes.grid": True,
    "grid.alpha": 0.3,
    "grid.linestyle": "--"
})

def get_latest_results_dir(base_dir: Path) -> Path | None:
    results_dir = base_dir / "results"
    if not results_dir.exists():
        return None
    subdirs = [d for d in results_dir.iterdir() if d.is_dir() and d.name.startswith("trd_")]
    if not subdirs:
        return None
    return max(subdirs, key=lambda d: d.name)

def plot_convergence(results_dir: Path, output_dir: Path) -> None:
    csv_path = results_dir / "convergence_summary.csv"
    if not csv_path.exists():
        print(f"Aviso: {csv_path.name} não encontrado. Pulando gráfico de convergência.")
        return

    df = pd.read_csv(csv_path)
    if df.empty:
        return

    # Filter a few representative instances to not clutter the plot
    # We select up to 5 instances of different sizes (e.g. cubic_100, cubic_500, cubic_1000, cubic_2000, cubic_3000)
    all_instances = df["instance"].unique()
    selected_instances = []
    for target in ["cubic_100.txt", "cubic_500.txt", "cubic_1000.txt", "cubic_2000.txt", "cubic_3000.txt"]:
        if target in all_instances:
            selected_instances.append(target)
    
    # If none of the specific targets are found, take a sample
    if not selected_instances:
        selected_instances = list(all_instances[:5])

    plt.figure(figsize=(8, 5))
    
    for inst in selected_instances:
        inst_df = df[df["instance"] == inst].sort_values("elapsed_seconds")
        # Normalize fitness by the initial/max value to compare convergence rates relatively
        max_val = inst_df["mean_global_best"].max()
        normalized_best = inst_df["mean_global_best"] / max_val if max_val > 0 else inst_df["mean_global_best"]
        
        plt.plot(
            inst_df["elapsed_seconds"],
            normalized_best,
            label=inst.replace(".txt", ""),
            linewidth=2
        )

    plt.xlabel("Tempo Decorrido (segundos)")
    plt.ylabel("Custo Normalizado (Fração do Inicial)")
    plt.title("Curva de Convergência do Blackboard (SMA)")
    plt.legend(loc="upper right")
    plt.tight_layout()
    
    plt.savefig(output_dir / "blackboard_convergence.png", dpi=300)
    plt.savefig(output_dir / "blackboard_convergence.pdf")
    plt.close()
    print("-> Gráfico 'blackboard_convergence' salvo.")

def plot_fitness_distribution(results_dir: Path, output_dir: Path) -> None:
    csv_path = results_dir / "raw_runs.csv"
    if not csv_path.exists():
        print(f"Aviso: {csv_path.name} não encontrado. Pulando gráfico de distribuição de fitness.")
        return

    df = pd.read_csv(csv_path)
    if df.empty:
        return

    # Select representative instances to plot
    all_instances = df["instance"].unique()
    selected = [inst for inst in ["cubic_100.txt", "cubic_300.txt", "cubic_500.txt", "cubic_800.txt", "cubic_1000.txt"] if inst in all_instances]
    if not selected:
        selected = list(all_instances[:5])

    # We will create a boxplot of the fitness values for these instances
    plot_data = []
    labels = []
    for inst in selected:
        inst_df = df[df["instance"] == inst]
        # Clean nan values
        costs = inst_df["best"].dropna().tolist()
        if costs:
            plot_data.append(costs)
            labels.append(inst.replace(".txt", ""))

    if not plot_data:
        return

    plt.figure(figsize=(8, 5))
    plt.boxplot(plot_data, patch_artist=True,
                boxprops=dict(facecolor="#D1E8E2", color="#1976D2"),
                medianprops=dict(color="#D32F2F", linewidth=2),
                whiskerprops=dict(color="#1976D2"),
                capprops=dict(color="#1976D2"))
    plt.gca().set_xticklabels(labels)
    
    plt.xlabel("Instância")
    plt.ylabel("Melhor Custo (TRD Weight)")
    plt.title("Distribuição do Custo (Fitness) entre as Rodadas")
    plt.tight_layout()
    
    plt.savefig(output_dir / "fitness_distribution.png", dpi=300)
    plt.savefig(output_dir / "fitness_distribution.pdf")
    plt.close()
    print("-> Gráfico 'fitness_distribution' salvo.")

